"""Generates apps/windows/src/Annotator.Core/Text/SwiftUnicodeData.g.cs.

Swift compares strings by canonical equivalence and maps case with the full Unicode mappings. .NET runs with
invariant globalization, where string normalization does nothing and casing uses simple mappings without the
Turkish i, so Annotator.Core carries the data it needs: canonical decompositions, combining classes, primary
composites and the full case mappings that are not one code point to one code point.

The data comes from the Unicode Character Database in Python's unicodedata module (Unicode License V3, see
THIRD_PARTY_NOTICES.md). Run from the repository root:

    python tools/windows/generate-unicode-tables.py
"""

import pathlib
import sys
import unicodedata

OUTPUT = pathlib.Path("apps/windows/src/Annotator.Core/Text/SwiftUnicodeData.g.cs")
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def characters():
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        yield code, chr(code)


def canonical_decomposition(character):
    text = unicodedata.decomposition(character)
    if not text or text.startswith("<"):
        return None
    return [int(part, 16) for part in text.split()]


def main():
    keys, firsts, seconds = [], [], []
    compositions = []
    classes = []
    special_upper, special_lower = [], []
    for code, character in characters():
        if not HANGUL_FIRST <= code <= HANGUL_LAST:
            parts = canonical_decomposition(character)
            if parts is not None:
                keys.append(code)
                firsts.append(parts[0])
                seconds.append(parts[1] if len(parts) > 1 else 0)
                if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == character:
                    compositions.append((parts[0], parts[1], code))
        combining = unicodedata.combining(character)
        if combining:
            if classes and classes[-1][1] == code - 1 and classes[-1][2] == combining:
                classes[-1][1] = code
            else:
                classes.append([code, code, combining])
        upper, lower = character.upper(), character.lower()
        if len(upper) > 1:
            special_upper.append((code, upper))
        if len(lower) > 1:
            special_lower.append((code, lower))
    # .NET's invariant casing leaves out the Turkish dotless i's simple mapping.
    special_upper.append((0x0131, "I"))
    special_upper.sort()
    compositions.sort()

    def numbers(values, per_line=12):
        lines = []
        for start in range(0, len(values), per_line):
            lines.append("        " + ", ".join(values[start:start + per_line]) + ",")
        return "\n".join(lines)

    def packed(text):
        value = 0
        for index, part in enumerate(text):
            value |= ord(part) << (21 * index)
        return value

    hexes = lambda items: ["0x%X" % item for item in items]
    out = []
    out.append("// <auto-generated>")
    out.append("// Generated by tools/windows/generate-unicode-tables.py from the Unicode Character Database %s" % unicodedata.unidata_version)
    out.append("// (Python %s unicodedata). Unicode data: Unicode License V3; see THIRD_PARTY_NOTICES.md." % sys.version.split()[0])
    out.append("// </auto-generated>")
    out.append("namespace Annotator.Core;")
    out.append("")
    out.append("internal static partial class SwiftUnicodeData")
    out.append("{")
    out.append('    public const string UnicodeVersion = "%s";' % unicodedata.unidata_version)
    out.append("")
    out.append("    /// <summary>Code points with a canonical decomposition, Hangul syllables excluded, in order.</summary>")
    out.append("    public static ReadOnlySpan<int> DecompositionKeys =>")
    out.append("    [")
    out.append(numbers(hexes(keys)))
    out.append("    ];")
    out.append("")
    out.append("    /// <summary>The first code point of each single-step canonical decomposition.</summary>")
    out.append("    public static ReadOnlySpan<int> DecompositionFirst =>")
    out.append("    [")
    out.append(numbers(hexes(firsts)))
    out.append("    ];")
    out.append("")
    out.append("    /// <summary>The second code point of each decomposition, or 0 for a singleton.</summary>")
    out.append("    public static ReadOnlySpan<int> DecompositionSecond =>")
    out.append("    [")
    out.append(numbers(hexes(seconds)))
    out.append("    ];")
    out.append("")
    out.append("    /// <summary>Canonical combining classes other than 0: first code point, last code point and class.</summary>")
    out.append("    public static ReadOnlySpan<int> CombiningClasses =>")
    out.append("    [")
    out.append(numbers(["0x%X, 0x%X, %d" % tuple(item) for item in classes], per_line=4))
    out.append("    ];")
    out.append("")
    out.append("    /// <summary>Primary composites, Hangul excluded: first &lt;&lt; 21 | second, in order.</summary>")
    out.append("    public static ReadOnlySpan<long> CompositionPairs =>")
    out.append("    [")
    out.append(numbers(["0x%X" % ((first << 21) | second) for first, second, _ in compositions], per_line=8))
    out.append("    ];")
    out.append("")
    out.append("    /// <summary>The composite of each pair in <see cref=\"CompositionPairs\"/>.</summary>")
    out.append("    public static ReadOnlySpan<int> Compositions =>")
    out.append("    [")
    out.append(numbers(hexes([composite for _, _, composite in compositions])))
    out.append("    ];")
    for name, table, summary in (
        ("Upper", special_upper, "Full uppercase mappings that .NET's invariant simple mapping does not give"),
        ("Lower", special_lower, "Full lowercase mappings that .NET's invariant simple mapping does not give"),
    ):
        out.append("")
        out.append("    /// <summary>%s: code points in order.</summary>" % summary)
        out.append("    public static ReadOnlySpan<int> Special%sKeys =>" % name)
        out.append("    [")
        out.append(numbers(hexes([code for code, _ in table])))
        out.append("    ];")
        out.append("")
        out.append("    /// <summary>The mapping of each key: up to three code points of 21 bits, first in the low bits.</summary>")
        out.append("    public static ReadOnlySpan<long> Special%sValues =>" % name)
        out.append("    [")
        out.append(numbers(["0x%X" % packed(text) for _, text in table], per_line=6))
        out.append("    ];")
    out.append("}")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("%s: %d decompositions, %d class ranges, %d composites, %d upper and %d lower special mappings"
          % (OUTPUT, len(keys), len(classes), len(compositions), len(special_upper), len(special_lower)))


if __name__ == "__main__":
    main()
