#!/usr/bin/env python3
"""Generate shared native vector artwork from pinned Lucide SVGs (build tool only)."""
from pathlib import Path
from urllib.request import urlopen
from fontTools.svgLib.path import SVGPath
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = Path(__file__).resolve().parents[2]
REVISION = "a79b2d131dab2bf20cb224bd0937b439a9c4fa99"
ICONS = {
    "databaseStack": "database", "server": "server", "messaging": "messages-square",
    "web": "globe", "mobile": "smartphone", "desktop": "monitor", "laptop": "laptop",
    "document": "file-text", "configuration": "settings", "loadBalancer": "network",
    "apiGateway": "square-arrow-right", "envelope": "mail", "cart": "shopping-cart", "bell": "bell",
}


def fetch(path):
    return urlopen(f"https://raw.githubusercontent.com/lucide-icons/lucide/{REVISION}/{path}", timeout=30).read()


def number(value):
    return f"{value:.8g}"


def point(value):
    return f"CGPoint(x: {number(value[0])}, y: {number(value[1])})"


def main():
    folder = ROOT / "tools/artwork/system-shapes"
    folder.mkdir(parents=True, exist_ok=True)
    license_file = ROOT / "apps/macos/Annotator/Lucide-LICENSE.txt"
    license_file.write_bytes(fetch("LICENSE"))
    lines = [
        "// Generated by tools/artwork/generate-system-symbols.py. See Lucide-LICENSE.txt.",
        f"// Lucide source: {REVISION}",
        "import CoreGraphics", "import AnnotationCore", "",
        "public enum SystemDiagramGeometry {",
        "    public static func path(for element: Element) -> CGPath {",
        "        let path = CGMutablePath()", "        let bounds: CGRect", "        switch element.tool {",
    ]
    ratios = []
    for tool, icon in ICONS.items():
        data = fetch(f"icons/{icon}.svg")
        (folder / f"{icon}.svg").write_bytes(data)
        pen = RecordingPen()
        SVGPath.fromstring(data).draw(pen)
        bounds_pen = BoundsPen(None)
        SVGPath.fromstring(data).draw(bounds_pen)
        x0, y0, x1, y1 = bounds_pen.bounds
        ratios.append(f"        case .{tool}: {number((x1-x0)/(y1-y0))}")
        if not pen.value:
            raise ValueError(f"No vector data for {icon}")
        lines.append(f"        case .{tool}:")
        lines.append(f"            bounds = CGRect(x: {number(x0)}, y: {number(y0)}, width: {number(x1-x0)}, height: {number(y1-y0)})")
        for operation, arguments in pen.value:
            if operation == "moveTo":
                line = f"path.move(to: {point(arguments[0])})"
            elif operation == "lineTo":
                line = f"path.addLine(to: {point(arguments[0])})"
            elif operation == "curveTo" and len(arguments) == 3:
                line = f"path.addCurve(to: {point(arguments[2])}, control1: {point(arguments[0])}, control2: {point(arguments[1])})"
            elif operation == "qCurveTo" and len(arguments) == 2 and arguments[1] is not None:
                line = f"path.addQuadCurve(to: {point(arguments[1])}, control: {point(arguments[0])})"
            elif operation == "closePath":
                line = "path.closeSubpath()"
            elif operation == "endPath":
                continue
            else:
                raise ValueError(f"Unsupported vector operation {icon}: {operation}")
            lines.append("            " + line)
    lines += [
        "        default: return path", "        }",
        "        let b = element.symbolFrame",
        "        let transform = CGAffineTransform(translationX: b.x, y: b.y)",
        "            .scaledBy(x: b.width/bounds.width, y: b.height/bounds.height)",
        "            .translatedBy(x: -bounds.minX, y: -bounds.minY)",
        "        let result = CGMutablePath()", "        result.addPath(path, transform: transform)",
        "        return result", "    }", "}", "",
    ]
    (ROOT / "apps/macos/Sources/PresentationRendering/SystemDiagramGeometry.swift").write_text("\n".join(lines))
    catalog = [
        "// Generated by tools/artwork/generate-system-symbols.py.",
        "import Foundation", "", "extension Tool {",
        "    public var systemShapeAspectRatio: Double? {", "        switch self {",
        *ratios, "        default: nil", "        }", "    }", "}", "",
        "extension Element {",
        "    public var symbolFrame: Rect {",
        "        guard let ratio = tool.systemShapeAspectRatio else { return frame }",
        "        let width = min(frame.width, frame.height * ratio)",
        "        let height = min(frame.height, frame.width / ratio)",
        "        return Rect(x: frame.center.x-width/2, y: frame.center.y-height/2, width: width, height: height)",
        "    }", "}", "",
    ]
    (ROOT / "apps/macos/Sources/AnnotationCore/SystemShapeCatalog.swift").write_text("\n".join(catalog))
    print(f"Generated {len(ICONS)} shared vector symbols.")


if __name__ == "__main__":
    main()
