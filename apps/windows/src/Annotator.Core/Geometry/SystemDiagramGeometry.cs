                path.CubicTo(new Point(20.395963, 17.000142), new Point(20.754716, 16.766635), new Point(20.914889, 16.404515));
                path.CubicTo(new Point(21.075062, 16.042395), new Point(21.006483, 15.619871), new Point(20.74, 15.327));
                path.CubicTo(new Point(19.41, 13.956), new Point(18, 12.499), new Point(18, 8));
                path.CubicTo(new Point(18, 4.6862915), new Point(15.313708, 2), new Point(12, 2));
                path.CubicTo(new Point(8.6862915, 2), new Point(6, 4.6862915), new Point(6, 8));
                path.CubicTo(new Point(6, 12.499), new Point(4.589, 13.956), new Point(3.262, 15.326));
                break;
            default:
                return PathData.Empty;
        }
        var b = element.SymbolFrame;
        var transform = AffineTransform.Translation(b.X, b.Y)
            .Scaled(b.Width / bounds.Width, b.Height / bounds.Height)
            .Translated(-bounds.X, -bounds.Y);
        return new PathBuilder(path.VerbCount, path.PointCount).AddPath(path.ToPathData(), transform).ToPathData();
    }
