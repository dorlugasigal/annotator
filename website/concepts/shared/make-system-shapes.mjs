// Writes system-shapes.js: the outlines of the app's system-design shapes (Database, Server, Messaging and the rest),
// read from apps/macos/Sources/PresentationRendering/SystemDiagramGeometry.swift. That file is generated from Lucide
// (ISC) by tools/artwork/generate-system-symbols.py. Run: node website/concepts/shared/make-system-shapes.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = readFileSync(new URL("../../../apps/macos/Sources/PresentationRendering/SystemDiagramGeometry.swift", import.meta.url), "utf8");
const point = "CGPoint\\(x: (-?[\\d.]+), y: (-?[\\d.]+)\\)";
const shapes = {};
let shape = null;
for (const line of source.split("\n")) {
  const name = /^\s*case \.(\w+):/.exec(line);
  if (name) { shape = shapes[name[1]] = { bounds: null, path: [] }; continue; }
  if (/^\s*default:/.test(line)) shape = null;
  if (!shape) continue;
  const bounds = /bounds = CGRect\(x: (-?[\d.]+), y: (-?[\d.]+), width: ([\d.]+), height: ([\d.]+)\)/.exec(line);
  if (bounds) { shape.bounds = bounds.slice(1).map(Number); continue; }
  const numbers = [...line.matchAll(new RegExp(point, "g"))].map((found) => [Number(found[1]), Number(found[2])]);
  if (/path\.move\(to:/.test(line)) shape.path.push(["move", [numbers[0]]]);
  else if (/path\.addLine\(to:/.test(line)) shape.path.push(["line", [numbers[0]]]);
  // addCurve(to:control1:control2:) names the end first; a path element lists it last.
  else if (/path\.addCurve\(to:/.test(line)) shape.path.push(["cubic", [numbers[1], numbers[2], numbers[0]]]);
  else if (/path\.closeSubpath\(\)/.test(line)) shape.path.push(["close"]);
  else if (/path\./.test(line)) throw new Error(`Unread path call: ${line.trim()}`);
}
for (const [name, { bounds, path }] of Object.entries(shapes)) if (!bounds || !path.length) throw new Error(`${name} has no outline.`);
const file = fileURLToPath(new URL("system-shapes.js", import.meta.url));
const body = Object.entries(shapes).map(([name, { bounds, path }]) => ` ${name}: { bounds: ${JSON.stringify(bounds)}, path: ${JSON.stringify(path)} },`).join("\n");
writeFileSync(file, `// Generated by make-system-shapes.mjs from apps/macos/Sources/PresentationRendering/SystemDiagramGeometry.swift
// (Lucide, ISC). Each outline is drawn in \`bounds\` ([x, y, width, height]) and fitted to the shape's symbol frame. Do not edit.
export const SYSTEM_SHAPE_PATHS = {\n${body}\n};\n`);
console.log(`${Object.keys(shapes).length} shapes -> ${file}`);
