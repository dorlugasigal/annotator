// Writes app-icons.js: the Windows edition's toolbar glyphs (Lucide, ISC, and Annotator's own drawings),
// keyed by the Mac symbol name each one stands for. Run: node website/concepts/shared/make-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const app = new URL("../../../apps/windows/src/Annotator.App/", import.meta.url);
const map = JSON.parse(readFileSync(new URL("Assets/icon-map.json", app), "utf8")).symbols;
const source = readFileSync(new URL("Icons/LucideIcons.g.cs", app), "utf8");
const icons = new Map();
for (const line of source.split("\n")) {
  const head = /new\("([^"]+)", \[(.*)\]\);/.exec(line);
  if (!head) continue;
  icons.set(head[1], [...head[2].matchAll(/new\("([^"]+)", (true|false)\)/g)].map(([, d, fill]) => ({ d: d.replace(/,/g, " "), fill: fill === "true" })));
}
const wanted = [
  "cursorarrow", "rectangle", "rectangle.fill", "diamond", "circle", "arrow.up.right", "line.diagonal", "pencil", "textformat",
  "highlighter", "laser.burst", "eraser", "camera.filters", "square.grid.2x2", "desktopcomputer", "pencil.tip",
  "arrow.uturn.backward", "arrow.uturn.forward", "trash", "slider.horizontal.3", "gearshape", "xmark", "chevron.down",
  "wand.and.stars", "1.circle", "aqi.medium", "scribble", "checkmark",
  "flashlight.on.fill", "circle.dotted", "light.beacon.max", "cursorarrow.rays", "square.grid.3x3.fill", "tornado",
  "bold", "text.alignleft", "text.aligncenter", "text.alignright", "square.dashed", "chevron.right", "chevron.up.chevron.down",
  "triangle", "hexagon", "star", "ruler", "photo.on.rectangle", "plus.magnifyingglass", "arrow.up.left.and.arrow.down.right",
  "rectangle.on.rectangle", "arrow.up.left.and.down.right.magnifyingglass", "eyedropper", "person", "cylinder", "grid", "chart.xyaxis.line",
];
const out = {};
for (const symbol of wanted) {
  const entry = map[symbol];
  const name = typeof entry === "string" ? entry : entry.lucide || entry.glyph;
  const parts = icons.get(name) || icons.get(`annotator/${name}`) || icons.get(`${name}-filled`);
  if (!parts) throw new Error(`No icon for ${symbol} (${name})`);
  out[symbol] = typeof entry === "object" && entry.fill ? parts.map((part) => ({ ...part, fill: true })) : parts;
}
const file = fileURLToPath(new URL("app-icons.js", import.meta.url));
writeFileSync(file, `// Generated by make-icons.mjs from apps/windows/src/Annotator.App/Icons (Lucide, ISC, and Annotator's own glyphs). Do not edit.\nexport const APP_ICONS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`${Object.keys(out).length} icons -> ${file}`);
